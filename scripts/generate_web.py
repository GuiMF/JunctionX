"""Generate TypeScript transport types from the backend's serialized JSON schemas."""

import json
from pathlib import Path

from core.models import ScanInput, ScanRequest, ScanResult


def typescript(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(typescript(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    if kind == "object":
        value = schema.get("additionalProperties", {})
        return f"Record<string, {typescript(value) if isinstance(value, dict) else 'any'}>"
    if kind in {"string", "boolean", "null"}:
        return kind
    if kind in {"integer", "number"}:
        return "number"
    if not schema:
        return "any"  # Matches backend Any, notably the score dictionary.
    raise ValueError(f"Unsupported TypeScript schema: {schema}")


def generate_types() -> str:
    definitions = {}
    for model in (ScanRequest, ScanResult):
        schema = model.model_json_schema(mode="serialization")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    lines = ["// Generated by python -m scripts.generate_contract. Do not edit.\n"]
    for name, schema in sorted(definitions.items()):
        lines.append(f"export interface {name} {{")
        for field, value in schema["properties"].items():
            # Responses include defaults; callers may omit request defaults.
            optional = name in {ScanInput.__name__, ScanRequest.__name__} and field not in schema.get("required", [])
            lines.append(f"  {field}{'?' if optional else ''}: {typescript(value)};")
        lines.append("}\n")
    return "\n".join(lines)


def write_types(root: Path) -> None:
    (root / "web/src/types/generated.ts").write_text(generate_types())
